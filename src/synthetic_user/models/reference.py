"""Reference data (design v3): any user-supplied file + optional usage guide, and the
per-scenario Reference Pack built from it.

The reference is never generated by this tool. Every item the LLM takes from it carries a
verbatim quote that code checks against the reference text (``Reference.contains``); items
whose quote is not found are rejected with a reason, never fixed.
"""

from __future__ import annotations

import re
from enum import StrEnum

from pydantic import Field, JsonValue

from synthetic_user.models.base import NonEmptyStr, StrictModel

# Used when the user gives a reference without a usage guide.
DEFAULT_GUIDE = (
    "Descriptive reference, not exhaustive. Treat what it states as authoritative and do not "
    "assume anything it does not state."
)


class ReferenceFormat(StrEnum):
    JSON = "json"
    TEXT = "text"
    MARKDOWN = "markdown"


# Straight, back and typographic quote marks (escaped: the source stays ASCII).
_QUOTE_MARKS = "\"'` \u201c\u201d\u2018\u2019"


def normalise_quote(text: str) -> str:
    """Whitespace-collapsed, case-folded text without surrounding quote marks or end
    punctuation, so a quote copied from pretty-printed JSON or wrapped prose still matches."""
    collapsed = re.sub(r"\s+", " ", text).strip().casefold()
    return collapsed.strip(_QUOTE_MARKS).rstrip(".,;:").strip()


class Reference(StrictModel):
    """The user's reference file as the tool uses it (JSON is re-indented for prompts)."""

    # "<file stem>-<sha256[:8] of text + guide>": an edited file or guide gets a new id.
    reference_id: NonEmptyStr
    source_name: NonEmptyStr
    format: ReferenceFormat
    text: NonEmptyStr
    guide: str | None = None
    guide_name: str | None = None

    def guide_text(self) -> str:
        return self.guide.strip() if self.guide and self.guide.strip() else DEFAULT_GUIDE

    def contains(self, quote: str) -> bool:
        needle = normalise_quote(quote)
        return bool(needle) and needle in normalise_quote(self.text)


class CoreRef(StrictModel):
    """Something a correct answer MUST rely on (a table, column, policy section, fact...)."""

    name: NonEmptyStr = Field(description="as the reference spells it")
    quote: NonEmptyStr = Field(description="short passage copied VERBATIM from the reference")
    why: NonEmptyStr = Field(description="why the scenario's goal needs it")


class ReferenceRule(StrictModel):
    """A constraint from the reference the answer must respect (e.g. default currency)."""

    rule: NonEmptyStr
    quote: NonEmptyStr = Field(description="passage copied VERBATIM from the reference")


class ReferencePackDraft(StrictModel):
    """LLM-facing (and user-editable) part of a Reference Pack."""

    core_refs: list[CoreRef] = Field(min_length=1)
    rules: list[ReferenceRule] = Field(default_factory=list)


class RejectedRefItem(StrictModel):
    item: dict[str, JsonValue]
    reason: NonEmptyStr


class ReferencePack(StrictModel):
    """The authoritative answer key of one grounded scenario."""

    pack_id: NonEmptyStr = Field(pattern=r"^RP_SCN_\d{3,}$")
    scenario_id: NonEmptyStr = Field(pattern=r"^SCN_\d{3,}$")
    reference_id: NonEmptyStr
    core_refs: list[CoreRef] = Field(min_length=1)
    rules: list[ReferenceRule] = Field(default_factory=list)
    # Items the generator proposed whose quote was not found in the reference.
    rejected_items: list[RejectedRefItem] = Field(default_factory=list)
    edited: bool = False  # True once a person changed it in the UI

    def view(self) -> dict[str, object]:
        """What prompts see: core refs and rules only."""
        return self.model_dump(mode="json", include={"core_refs", "rules"})


def pack_id_for(scenario_id: str) -> str:
    return f"RP_{scenario_id}"
