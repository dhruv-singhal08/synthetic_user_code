"""Prompt for Node 5 Stage B: LLM review of product-generated SQL against metadata."""

from __future__ import annotations

import json

from synthetic_user.models.evaluation import SqlAnalysis, SqlEvaluationDraft
from synthetic_user.models.product import ProductDescription
from synthetic_user.models.question import QuestionCase
from synthetic_user.models.reference import ReferenceSnapshot
from synthetic_user.models.scenario import Scenario
from synthetic_user.prompts.evaluation_context import evaluation_context

SYSTEM = (
    "You review SQL produced by an NL2SQL product for a business question. You judge only "
    "what the SQL and the schema metadata show; you cannot see data or results. "
    "You reply with a single JSON object and nothing else."
)


def build_sql_evaluation_prompt(
    question: QuestionCase,
    scenario: Scenario,
    snapshot: ReferenceSnapshot,
    product: ProductDescription,
    sql: str,
    sql_analysis: SqlAnalysis | None,
) -> tuple[str, str]:
    analysis = (
        json.dumps(sql_analysis.model_dump(mode="json"), indent=2)
        if sql_analysis is not None
        else "Not available (no static analysis was run)."
    )
    schema = json.dumps(SqlEvaluationDraft.model_json_schema(), indent=2)
    user = f"""## TASK
Evaluate whether the SQL below correctly answers the user's question, given the schema
metadata. Fill every check, report findings, list cheat-sheet conflicts, give a verdict.

## INPUT
{evaluation_context(question, scenario, snapshot, product)}

SQL generated by the product:
```sql
{sql}
```

Static SQL analysis (JSON):
{analysis}

## CONSTRAINTS
- The snapshot is authoritative. The cheat sheet is only a reference path: alternative SQL
  that correctly answers the question is acceptable and must not fail for differing from it.
- Do not report a "missing join" when the table already used has the needed dimension.
- checks: pass | fail | inconclusive | not_applicable for each. Use not_applicable when a
  check does not apply (e.g. join_correctness with no joins, aggregation_correctness with
  no aggregation).
- Every failed check needs at least one finding whose category is that check's name
  (e.g. "join_correctness") and whose sql_evidence is an exact fragment copied from the SQL.
- Use inconclusive (not fail) when the metadata is insufficient to decide.
- verdict: fail if any check fails; pass only if no check fails and nothing is inconclusive
  that matters for the question; otherwise inconclusive.
- Set matches_known_gap true when a finding matches one of the product's known_gaps.
- cheat_sheet_conflicts: places where the cheat sheet disagrees with the snapshot metadata.

## OUTPUT CONTRACT
Return one JSON object matching this JSON Schema:
{schema}

## PROHIBITED
- Claiming the numeric result is correct or incorrect (you cannot see results).
- Failing SQL only because it differs from the cheat sheet.
- sql_evidence that is not copied verbatim from the SQL.
- ids, timestamps, or any text outside the JSON object.

## MISSING INFO
If the snapshot lacks what you need (missing_references, unknown relationships), mark the
affected checks inconclusive and say why in a finding or cheat_sheet_conflicts.
"""
    return SYSTEM, user
